/**
 * Next.js 16.2 probes `typescript/lib/typescript.js` to detect TypeScript.
 * TypeScript 7 (native) does not ship that JS API file, so Next mis-detects
 * TS as missing and crashes. Write a tiny shim when the real file is absent.
 */
import { existsSync, mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(fileURLToPath(new URL(".", import.meta.url)), "..");
const target = join(root, "node_modules/typescript/lib/typescript.js");
const pkg = join(root, "node_modules/typescript/package.json");

if (!existsSync(pkg)) {
  process.exit(0);
}

if (existsSync(target)) {
  process.exit(0);
}

mkdirSync(dirname(target), { recursive: true });
writeFileSync(
  target,
  [
    "// Generated by scripts/patch-typescript-for-next.mjs",
    "// Satisfies Next.js 16.2 TypeScript detection for typescript@7 (native).",
    'module.exports = require("../lib/version.cjs");',
    "",
  ].join("\n"),
);
console.log("patched typescript/lib/typescript.js for Next.js");
